export function getDefaultReportCardDesign(college: College): ReportCardDesignConfig {
  const primary = college.colores?.primario || '#0B2545';
  const secondary = college.colores?.secundario || '#C59B27';

  if (college.disenoBoleta && Array.isArray(college.disenoBoleta.elementos) && college.disenoBoleta.elementos.length > 0) {
    const hasTeacherSig = college.disenoBoleta.elementos.some(
      (el) => el.type === 'firma_docente'
    );
    if (!hasTeacherSig) {
      const tutorEl = college.disenoBoleta.elementos.find((el) => el.type === 'firma_tutor');
      const updatedElements: ReportCardCanvasElement[] = [
        ...college.disenoBoleta.elementos.map((el) =>
          el.type === 'firma_tutor' ? { ...el, visible: false } : el
        ),
        {
          id: 'el-firma-docente',
          type: 'firma_docente',
          label: 'Firma del Docente',
          visible: true,
          x: tutorEl?.x ?? 67,
          y: tutorEl?.y ?? 81.5,
          w: tutorEl?.w ?? 27,
          h: tutorEl?.h ?? 11,
          textAlign: 'center',
          textColor: '#1E293B',
          showBorder: false,
          fontSizeScale: 1,
          zIndex: 8,
        },
      ];
      return {
        ...college.disenoBoleta,
        firmaSecundariaTipo: college.disenoBoleta.firmaSecundariaTipo || 'docente',
        elementos: updatedElements,
      };
    }
    return {
      ...college.disenoBoleta,
      firmaSecundariaTipo: college.disenoBoleta.firmaSecundariaTipo || 'docente',
    };
  }

  return {
    usarDisenoPersonalizado: true,
    plantillaId: 'clasica',
    firmaSecundariaTipo: 'docente',
    colorFondoHoja: '#FFFFFF',
    imagenFondoUrl: '',
    opacidadImagenFondo: 0.2,
    marcaAguaEscudo: true,
    opacidadMarcaAgua: 0.05,
    mostrarMarcoDecorativo: true,
    estiloMarco: 'doble_institucional',
    colorMarco: SEP_OFFICIAL_COLORS.guinda,
    colorEncabezadoTabla: SEP_OFFICIAL_COLORS.guinda,
    colorTextoTabla: '#1E1E1E',
    colorAcento: SEP_OFFICIAL_COLORS.dorado,
    elementos: getPresetElements('clasica', college),
  };
}
