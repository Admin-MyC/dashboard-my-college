export function resolveStudentTeacherName(
  student: Student,
  college?: College | null,
  teachers: Teacher[] = []
): string {
  if (student.docenteNombre && student.docenteNombre.trim()) {
    return student.docenteNombre.trim();
  }
  const collegeTeachers = college
    ? teachers.filter((t) => t.colegioId === college.id)
    : teachers;

  if (student.docenteId) {
    const byId = collegeTeachers.find((t) => t.id === student.docenteId);
    if (byId?.nombre) return byId.nombre;
  }

  const stLevel = resolveStudentEffectiveLevel(student, college);
  const stGrado = (student.grado || '').trim();
  const stGrupo = (student.grupo || '').replace(/["']/g, '').trim().toUpperCase();
  const cleanGradeGroup = `${stGrado} ${stGrupo}`.replace(/\s+/g, ' ').trim().toLowerCase();
  const cleanFullGroup = `${stLevel} ${stGrado} ${stGrupo}`.replace(/\s+/g, ' ').trim().toLowerCase();

  // Buscar tutor titular del grupo primero
  const groupTutor = collegeTeachers.find(
    (t) =>
      Boolean(t.esTutorPrincipal) &&
      (t.grupoTutorado || '').replace(/["']/g, '').replace(/\s+/g, ' ').trim().toLowerCase() ===
        cleanGradeGroup
  );
  if (groupTutor?.nombre) return groupTutor.nombre;

  // Buscar docente asignado al grupo
  const groupTeacher = collegeTeachers.find((t) => {
    const tchLvl = (t.nivel || '').trim().toLowerCase();
    if (tchLvl && tchLvl !== stLevel.toLowerCase()) return false;
    return (t.grupos || []).some((g) => {
      const norm = g.replace(/["']/g, '').replace(/\s+/g, ' ').trim().toLowerCase();
      return norm === cleanFullGroup || norm === cleanGradeGroup;
    });
  });
  if (groupTeacher?.nombre) return groupTeacher.nombre;

  return 'Docente Titular de Grupo';
}

